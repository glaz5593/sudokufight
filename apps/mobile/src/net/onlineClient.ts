import { Client, type EndpointSettings } from '@colyseus/sdk';
import type { GameType } from '@sudoku-fight/engine';
import {
  type ClientMessage,
  type ClientMessageType,
  type DevJoinOptions,
  GAME_ROOM_NAME,
  type GameRoomCreateOptions,
  type GameRoomRuleOverrides,
  type MatchSeatReservation,
  normalizeRoomCode,
  type ServerMessage,
  type ServerMessageType,
} from '@sudoku-fight/protocol';

import { OnlineError, onlineErrorOf } from './errors';

/**
 * The way into the game server (stage 7): create a private room, join one by its code, come back with a
 * reconnection token; and (stage 9) take the seat matchmaking reserved in a ranked match's room. It hides the Colyseus SDK behind a small interface (RoomLike), so RemoteGameHost runs
 * on any of: the SDK on the phone, the SDK in a Node test against the real server, a fake in Jest.
 *
 * Who the player is comes from an IdentitySource, asked again on every join (a Firebase ID token expires
 * after an hour; a rejoin needs a fresh one):
 * - until stage 8 a dev identity ({ devUserId, name } in the join options; refused by a production server);
 * - stage 8: a token, sent as the SDK's auth token (`client.auth.token`, the Authorization header).
 *
 * Every refusal comes out as an OnlineError (errors.ts). Pure: no React Native or Expo imports.
 */

/** Who is joining. */
export type NetIdentity =
  /** Until stage 8: the dev identity (protocol DevJoinOptions). */
  | ({ kind: 'dev' } & DevJoinOptions)
  /** Stage 8: a Firebase ID token. A bearer secret: never logged. */
  | { kind: 'token'; token: string };

/** Asked on every create and join. */
export type IdentitySource = () => Promise<NetIdentity>;

/** A joined room, as RemoteGameHost uses it. */
export interface RoomLike {
  /** The room's code. */
  readonly roomId: string;
  /** Comes back into this seat after a drop. A bearer secret: kept in memory only, never logged. */
  readonly reconnectionToken: string;
  onMessage(type: ServerMessageType, callback: (message: ServerMessage) => void): void;
  /** The connection is gone: closed by the server, dropped, or left. */
  onLeave(callback: (code: number) => void): void;
  onError(callback: (code: number, message?: string) => void): void;
  send(type: ClientMessageType, message: ClientMessage): void;
  /** Consented: leaving on purpose. Not consented: the socket just closes (the server sees a drop). */
  leave(consented: boolean): Promise<unknown>;
}

/** What a dev room is made with (protocol GameRoomCreateOptions, without who is joining). */
export interface DevRoomOptions {
  /** Default 'fast'. */
  gameType?: GameType;
  /** 2–4, default 2. */
  playerCount?: number;
  /** Dev and test rules (e.g. a short grace). */
  rules?: GameRoomRuleOverrides;
  /** A code of your own; generated by the server when absent. */
  code?: string;
}

export interface OnlineClient {
  /** Creates a private room and joins it (stage 7: outside production only). */
  create(options: DevRoomOptions): Promise<RoomLike>;
  /** Joins the room with this code, as typed (case, spaces and dashes don't matter). */
  join(code: string): Promise<RoomLike>;
  /** Back into the seat the token holds, after a drop. */
  reconnect(token: string): Promise<RoomLike>;
  /**
   * Into a ranked match's room (stage 9): the seat matchmaking reserved for this player (protocol
   * matchmaking.ts `found`). The reservation carries who it is, so no identity is asked.
   */
  consumeSeatReservation(reservation: MatchSeatReservation): Promise<RoomLike>;
}

/** The parts of an SDK Room used here. */
export interface SdkRoomLike {
  roomId: string;
  reconnectionToken: string;
  reconnection: { enabled: boolean };
  onMessage(type: string, callback: (message: ServerMessage) => void): unknown;
  onLeave(callback: (code: number, reason?: string) => void): unknown;
  onError(callback: (code: number, message?: string) => void): unknown;
  send(type: string, message: unknown): void;
  leave(consented?: boolean): Promise<number>;
}

/** The parts of the SDK Client used here. */
export interface SdkClientLike {
  auth: { token: string | undefined };
  create(roomName: string, options: object): Promise<SdkRoomLike>;
  joinById(roomId: string, options: object): Promise<SdkRoomLike>;
  reconnect(token: string): Promise<SdkRoomLike>;
  consumeSeatReservation(reservation: MatchSeatReservation): Promise<SdkRoomLike>;
}

export interface OnlineClientOptions {
  /** The server: `{ hostname, port, secure }` on the phone (React Native's URL can't parse ws://), or a URL. */
  endpoint?: string | EndpointSettings;
  /** An SDK client of your own (tests); otherwise one is made for `endpoint`. */
  sdk?: SdkClientLike;
  identity: IdentitySource;
}

/** An SDK room as a RoomLike. Reconnecting is RemoteGameHost's job, with the grace period in view. */
export function roomOf(room: SdkRoomLike): RoomLike {
  room.reconnection.enabled = false;
  return {
    get roomId() {
      return room.roomId;
    },
    get reconnectionToken() {
      return room.reconnectionToken;
    },
    onMessage: (type, callback) => void room.onMessage(type, callback),
    onLeave: (callback) => void room.onLeave((code) => callback(code)),
    onError: (callback) => void room.onError(callback),
    send: (type, message) => room.send(type, message),
    leave: (consented) => room.leave(consented),
  };
}

export function createOnlineClient({ endpoint, sdk, identity }: OnlineClientOptions): OnlineClient {
  const client: SdkClientLike = sdk ?? new Client(endpoint ?? 'ws://localhost:2567');

  /** Who is joining: the dev identity goes into the options; a token into the SDK's Authorization header. */
  const whoAmI = async (): Promise<Partial<DevJoinOptions>> => {
    const id = await identity();
    if (id.kind === 'token') {
      client.auth.token = id.token;
      return {};
    }
    return { devUserId: id.devUserId, name: id.name };
  };

  /** Runs an SDK call; every failure comes out as an OnlineError. */
  const call = async (open: () => Promise<SdkRoomLike>): Promise<RoomLike> => {
    try {
      return roomOf(await open());
    } catch (error) {
      throw onlineErrorOf(error);
    }
  };

  return {
    create: (options) =>
      call(async () => {
        const create: Omit<GameRoomCreateOptions, keyof DevJoinOptions> & Partial<DevJoinOptions> = {
          private: true,
          ...(await whoAmI()),
          ...options,
        };
        return client.create(GAME_ROOM_NAME, create);
      }),

    join: async (typed) => {
      const code = normalizeRoomCode(typed);
      if (code === null) throw new OnlineError('badCode', `"${typed}" is not a room code`);
      return call(async () => client.joinById(code, await whoAmI()));
    },

    reconnect: (token) => call(() => client.reconnect(token)),

    consumeSeatReservation: (reservation) => call(() => client.consumeSeatReservation(reservation)),
  };
}
