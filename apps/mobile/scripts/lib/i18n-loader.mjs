/**
 * The pure parts of `npm run i18n:gen` (scripts/gen-i18n-loader.mjs; localization plan 0ב, D119): the app's
 * strings are read one language at a time. src/i18n/locales.generated.ts has a function per language folder of
 * src/i18n/locales, with a require() of each namespace file inside it, so Metro bundles every language but none
 * of them runs before i18next asks for it (the chosen language and English at the start, another one right
 * before the app switches to it). The namespaces are the en folder's files. Types in i18n-loader.d.mts; the test
 * (src/i18n/__tests__/localeLoaders.test.ts) fails while the file on disk is not what this writes.
 */
import { existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

/** The source language: its folder's files are the namespaces, and it comes first. */
export const SOURCE_LANGUAGE = 'en';

/** The generated file, relative to apps/mobile. */
export const LOADER_PATH = 'src/i18n/locales.generated.ts';

/** The language folders, relative to apps/mobile. */
export const LOCALES_PATH = 'src/i18n/locales';

/**
 * Each language folder of `localesDir` with its namespace files (names without .json, sorted). The source
 * language first, then the others by code.
 *
 * @param {string} localesDir
 * @returns {{ language: string; namespaces: string[] }[]}
 */
export function scanLocales(localesDir) {
  if (!existsSync(localesDir)) return [];
  const languages = readdirSync(localesDir)
    .filter((name) => statSync(join(localesDir, name)).isDirectory())
    .sort((a, b) => (a === SOURCE_LANGUAGE ? -1 : b === SOURCE_LANGUAGE ? 1 : a < b ? -1 : a > b ? 1 : 0));
  return languages.map((language) => ({
    language,
    namespaces: readdirSync(join(localesDir, language))
      .filter((f) => f.endsWith('.json'))
      .map((f) => f.slice(0, -'.json'.length))
      .sort(),
  }));
}

/** A key as Prettier writes it: bare when it is an identifier, else quoted ('pt-BR'). */
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

/**
 * The loader's source text (Prettier's format, so `npm run format` leaves it alone). A namespace a language has
 * no file for yet is an empty object: i18next shows English for its keys (D101).
 *
 * @param {readonly { language: string; namespaces: readonly string[] }[]} locales
 * @returns {string}
 */
export function renderLocaleLoaders(locales) {
  const source = locales.find((l) => l.language === SOURCE_LANGUAGE);
  if (!source) throw new Error(`No ${SOURCE_LANGUAGE} folder: the namespaces are its files`);
  const namespaces = [...source.namespaces].sort();
  const lines = [
    '// Generated by scripts/gen-i18n-loader.mjs (`npm run i18n:gen` in apps/mobile) from src/i18n/locales.',
    '// Do not edit: after adding or removing a namespace file or a language folder, run it again',
    '// (src/i18n/__tests__/localeLoaders.test.ts fails until then). Localization plan 0ב.',
    '',
    "/** The namespaces: one JSON file each in every language folder (the en folder's files). */",
    'export const NAMESPACES = [',
    ...namespaces.map((ns) => `  '${ns}',`),
    '] as const;',
    'export type Namespace = (typeof NAMESPACES)[number];',
    '',
    "/** A language's strings: each namespace's JSON. */",
    'export type LocaleBundle = Readonly<Record<Namespace, object>>;',
    '',
    '/**',
    " * Each language folder's strings, read when its function is first called (a require() inside a function runs",
    ' * only then: startupGraph.test.ts). i18n/index.ts calls them for the language the app starts in and English.',
    ' */',
    'export const LOCALE_LOADERS: Readonly<Record<string, () => LocaleBundle>> = {',
  ];
  for (const { language, namespaces: files } of locales) {
    lines.push(`  ${key(language)}: () => ({`);
    for (const ns of namespaces) {
      lines.push(
        files.includes(ns)
          ? `    ${key(ns)}: require('./locales/${language}/${ns}.json'),`
          : `    ${key(ns)}: {},`,
      );
    }
    lines.push('  }),');
  }
  lines.push('};', '');
  return lines.join('\n');
}
