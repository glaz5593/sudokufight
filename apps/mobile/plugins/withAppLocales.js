/**
 * The app's languages in the native projects (localization plan §1 and 0יא; D103, D118): the list the system
 * settings offer for this app, from the one list the app, scripts/i18n-check.mjs and this plugin share,
 * src/i18n/enabled-languages.json (each language stage adds its code there).
 *
 * - Android 13+: res/xml/locales_config.xml and `android:localeConfig` on the application, so Settings > Apps >
 *   Sudoku Fight > Language lists them (the per-app language the app reads and writes through
 *   modules/app-locale, src/services/appLocale.ts).
 * - iOS: CFBundleLocalizations in Info.plist, so Settings > Sudoku Fight > Language lists them.
 *
 * Why not expo-localization's own `supportedLocales`: besides the same two things, it adds
 * `resourceConfigurations += ["b+he", "b+zh+Hans", "b+pt+BR", …]` to android/app/build.gradle
 * (withExpoLocalization.js), which keeps only those resource folders of every library. The libraries' folders
 * are values-iw, values-in, values-zh-rCN, values-zh-rTW, values-pt…, and whether AAPT matches them to those
 * qualifiers is unverified: their Hebrew, Indonesian, Chinese and Portuguese strings (TalkBack's role names,
 * for one) could go. This plugin filters nothing. The first APK of the project checks the values-* folders
 * with `aapt2 dump` against the 19 languages (plan 0יא).
 *
 * The tags are the app's own codes, written as they are (BCP-47): `he` and `id`, `zh-Hans` and `zh-Hant` by
 * script, `pt-BR`. Android's LocaleConfig reads the names with LocaleList.forLanguageTags (AOSP
 * LocaleConfig.parseLocaleConfig, through a HashSet, so the order here doesn't matter), and Locale maps he and
 * iw, id and in, to the same locale: the old codes that Android's own sample file uses (developer.android.com,
 * "Per-app language preferences") and that the libraries' folders carry (values-iw, values-in) are the same
 * language, and Locale.toLanguageTag gives he and id back to the app. Which system languages Settings offers
 * under zh-Hans and zh-Hant is up to the phone: unverified until the first APK. iOS's localization names are
 * the same codes. The pseudo-languages (en-XA, ar-XB) live in JS only and are never listed.
 *
 * app.json passes the list's path (`languagesFile`): `npm run apk` hashes every file app.json names
 * (scripts/lib/build-apk.mjs appJsonFiles), so adding a language regenerates the android folder.
 */
const fs = require('fs');
const path = require('path');
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  withInfoPlist,
} = require('expo/config-plugins');

/** The shared list of the app's languages (relative to the project root, apps/mobile). */
const DEFAULT_LANGUAGES_FILE = './src/i18n/enabled-languages.json';

/** res/xml/locales_config.xml, by its resource name. */
const LOCALES_CONFIG_RESOURCE = '@xml/locales_config';

/** Where the file goes in the android folder. */
const LOCALES_CONFIG_PATH = ['app', 'src', 'main', 'res', 'xml', 'locales_config.xml'];

/** The JS-only pseudo-languages' regions (en-XA, ar-XB): never a native language. */
const PSEUDO_REGION = /-(?:XA|XB)$/i;

/**
 * The languages of the list's JSON: a non-empty array of distinct BCP-47 tags in canonical form ("zh-Hans",
 * not "zh-hans"; "he" and "id", not the old "iw" and "in"), none of them a pseudo-language. Throws, naming
 * the file and the tag, on anything else: a wrong list must never reach a build.
 */
function parseLanguages(json, source = DEFAULT_LANGUAGES_FILE) {
  const fail = (why) => {
    throw new Error(`withAppLocales: ${source} ${why}`);
  };
  if (!Array.isArray(json) || json.length === 0) fail('must be a non-empty JSON array of language codes');
  const seen = new Set();
  for (const tag of json) {
    if (typeof tag !== 'string') fail(`holds ${JSON.stringify(tag)}, which is not a language code`);
    let canonical;
    try {
      [canonical] = Intl.getCanonicalLocales(tag);
    } catch {
      fail(`holds "${tag}", which is not a BCP-47 language tag`);
    }
    if (canonical !== tag) fail(`holds "${tag}": write it as "${canonical}"`);
    if (PSEUDO_REGION.test(tag)) fail(`holds the pseudo-language "${tag}", which exists in JS only`);
    if (seen.has(tag)) fail(`holds "${tag}" twice`);
    seen.add(tag);
  }
  return [...json];
}

/** The languages from the list's file (`file` relative to `projectRoot`). */
function readLanguages(projectRoot, file = DEFAULT_LANGUAGES_FILE) {
  const full = path.resolve(projectRoot, file);
  let json;
  try {
    json = JSON.parse(fs.readFileSync(full, 'utf8'));
  } catch (error) {
    throw new Error(`withAppLocales: cannot read ${file} (${full}): ${error.message}`);
  }
  return parseLanguages(json, file);
}

/** res/xml/locales_config.xml for the languages. */
function localesConfigXml(languages) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withAppLocales.js from src/i18n/enabled-languages.json. -->',
    '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">',
    ...languages.map((tag) => `  <locale android:name="${tag}"/>`),
    '</locale-config>',
    '',
  ].join('\n');
}

/** The manifest with `android:localeConfig` on its application. */
function setLocaleConfig(manifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  application.$ = { ...application.$, 'android:localeConfig': LOCALES_CONFIG_RESOURCE };
  return manifest;
}

/** Info.plist with the languages as the app's localizations. */
function setBundleLocalizations(infoPlist, languages) {
  return { ...infoPlist, CFBundleLocalizations: [...languages] };
}

/** @type {import('expo/config-plugins').ConfigPlugin<{ languagesFile?: string } | void>} */
const withAppLocales = (config, options) => {
  const file = (options && options.languagesFile) || DEFAULT_LANGUAGES_FILE;
  let result = withDangerousMod(config, [
    'android',
    (mod) => {
      const languages = readLanguages(mod.modRequest.projectRoot, file);
      const target = path.join(mod.modRequest.platformProjectRoot, ...LOCALES_CONFIG_PATH);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, localesConfigXml(languages));
      return mod;
    },
  ]);
  result = withAndroidManifest(result, (mod) => {
    mod.modResults = setLocaleConfig(mod.modResults);
    return mod;
  });
  result = withInfoPlist(result, (mod) => {
    mod.modResults = setBundleLocalizations(mod.modResults, readLanguages(mod.modRequest.projectRoot, file));
    return mod;
  });
  return result;
};

module.exports = withAppLocales;
module.exports.DEFAULT_LANGUAGES_FILE = DEFAULT_LANGUAGES_FILE;
module.exports.LOCALES_CONFIG_RESOURCE = LOCALES_CONFIG_RESOURCE;
module.exports.LOCALES_CONFIG_PATH = LOCALES_CONFIG_PATH;
module.exports.parseLanguages = parseLanguages;
module.exports.readLanguages = readLanguages;
module.exports.localesConfigXml = localesConfigXml;
module.exports.setLocaleConfig = setLocaleConfig;
module.exports.setBundleLocalizations = setBundleLocalizations;
