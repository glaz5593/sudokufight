export const STRINGS: Record<Lang, Record<StringKey, string>> = { he, en };

export type Vars = Record<string, string | number>;

/** The string for `key` in `lang`, with each `{name}` replaced by vars[name] (left as is when missing). */
export function translate(lang: Lang, key: StringKey, vars?: Vars): string {
  const text = STRINGS[lang][key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function isStringKey(key: string): key is StringKey {
  return Object.hasOwn(he, key);
}

export function isLang(value: unknown): value is Lang {
  return value === 'he' || value === 'en';
}

/**
 * Wraps left-to-right text (an id, a screen name, a signed number) in Unicode isolates (LRI…PDI), so a
 * Hebrew sentence around it keeps its order and the sign stays on the right side (CLAUDE.md).
 */
export function isolate(text: string | number): string {
  return `\u2066${text}\u2069`;
}
