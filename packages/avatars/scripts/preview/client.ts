// Text, language, wiring

function renderText(): void {
  const root = $<HTMLElement>('#app');
  root.lang = state.lang;
  root.dir = state.lang === 'he' ? 'rtl' : 'ltr';
  for (const el of document.querySelectorAll<HTMLElement>('[data-t]')) {
    const key = el.dataset.t as keyof typeof UI | undefined;
    if (key && key in UI) el.textContent = t(UI[key]);
  }
  for (const el of document.querySelectorAll<HTMLElement>('[data-t-label]')) {
    const key = el.dataset.tLabel as keyof typeof UI | undefined;
    if (key && key in UI) el.setAttribute('aria-label', t(UI[key]));
  }
  $('#lead').textContent = t(UI.lead, { n: AVATARS.length, e: EXPRESSIONS.length, m: MOTION_IDS.length });
  $('#lang').textContent = t(UI.otherLang);
  $<HTMLInputElement>('#q').placeholder = t(UI.searchHint);
  // The command is LTR inside RTL text: isolate it so its punctuation stays put.
  $('#footer').innerHTML = t(UI.footer, {
    cmd: '<code dir="ltr">npm run preview -w @sudoku-fight/avatars</code>',
  });
  $<HTMLInputElement>('#opt-blink').checked = state.blink;
  $<HTMLInputElement>('#opt-idle').checked = state.idle;
  $<HTMLInputElement>('#opt-reduce').checked = state.reduceManual;
  for (const b of document.querySelectorAll<HTMLButtonElement>('[data-ground]'))
    if (b.tagName === 'BUTTON') b.setAttribute('aria-pressed', String(b.dataset.ground === state.ground));
}

function renderAll(): void {
  renderText();
  renderFilters();
  renderGrid();
  renderStage();
}

function setExpression(e: Expression): void {
  state.expression = e;
  stopMotion();
  setStageFace(e);
  for (const b of document.querySelectorAll<HTMLElement>('#faces [data-expression]'))
    b.setAttribute('aria-pressed', String(b.dataset.expression === e));
}

function select(id: string, scroll: boolean): void {
  if (!AVATARS.some((a) => a.id === id)) return;
  state.id = id;
  state.expression = 'neutral';
  state.playAll = false;
  for (const c of document.querySelectorAll<HTMLElement>('#grid .card'))
    c.setAttribute('aria-pressed', String(c.dataset.id === id));
  renderStage();
  try {
    if (window.location.hash !== `#${id}`) window.history.replaceState(null, '', `#${id}`);
  } catch {
    // a sandbox without history: the page works without the link
  }
  // Beside the grid the stage is always in view; above it, bring it back.
  if (scroll && !wideQuery.matches) $('#stage').scrollIntoView({ behavior: reduced() ? 'auto' : 'smooth' });
}

document.addEventListener('click', (ev) => {
  const el = (ev.target as Element | null)?.closest<HTMLElement>('button');
  if (!el) return;
  const d = el.dataset;
  if (d.id) select(d.id, true);
  else if (d.filter) {
    state.filter = d.filter as Filter;
    renderFilters();
    renderGrid();
  } else if (d.expression) {
    state.playAll = false;
    setExpression(d.expression as Expression);
    renderButtons();
  } else if (d.motion) {
    state.playAll = false;
    void play(d.motion as MotionId);
  } else if (el.id === 'play-all') {
    if (state.playAll) {
      state.playAll = false;
      stopMotion();
      renderButtons();
    } else void playAll();
  } else if (d.ground) {
    state.ground = d.ground as Ground;
    store.set('ground', state.ground);
    $<HTMLElement>('#ground').dataset.ground = state.ground;
    renderText();
  } else if (el.id === 'lang') {
    state.lang = state.lang === 'he' ? 'en' : 'he';
    store.set('lang', state.lang);
    renderAll();
  }
});

$<HTMLInputElement>('#q').addEventListener('input', (ev) => {
  state.query = (ev.target as HTMLInputElement).value;
  renderFilters();
  renderGrid();
});
$<HTMLInputElement>('#opt-blink').addEventListener('change', (ev) => {
  state.blink = (ev.target as HTMLInputElement).checked;
});
$<HTMLInputElement>('#opt-idle').addEventListener('change', (ev) => {
  state.idle = (ev.target as HTMLInputElement).checked;
  $('#big svg').classList.toggle('sfa-idle', state.idle);
});
$<HTMLInputElement>('#opt-reduce').addEventListener('change', (ev) => {
  state.reduceManual = (ev.target as HTMLInputElement).checked;
  document.documentElement.classList.toggle('sfa-reduce', state.reduceManual);
  renderStatus();
});
reduceQuery.addEventListener('change', renderStatus);
window.addEventListener('hashchange', () => {
  const id = fromHash();
  if (id && id !== state.id) select(id, true);
});

styleSheet('sfa-motion-css').textContent = motionCss();
renderAll();
scheduleBlink();
