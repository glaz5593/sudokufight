// ---------------------------------------------------------------------------------------------------------
// State

const data = JSON.parse(document.getElementById('sfa-data')?.textContent ?? '{}') as {
  avatars?: AvatarDef[];
};
const AVATARS = data.avatars ?? [];

const store = {
  get(key: string): string | null {
    try {
      return localStorage.getItem(`sfa-preview-${key}`);
    } catch {
      return null;
    }
  },
  set(key: string, value: string): void {
    try {
      localStorage.setItem(`sfa-preview-${key}`, value);
    } catch {
      // private window or blocked storage: the page works without it
    }
  },
};

const savedLang: Lang = store.get('lang') === 'en' ? 'en' : 'he';
const savedGround: Ground = store.get('ground') === 'board' ? 'board' : 'app';

const state = {
  lang: savedLang,
  ground: savedGround,
  filter: 'all' as Filter,
  id: AVATARS[0]?.id ?? '',
  expression: 'neutral' as Expression,
  playing: null as MotionId | null,
  playAll: false,
  blink: true,
  reduceManual: false,
};

const reduceQuery = window.matchMedia('(prefers-reduced-motion: reduce)');
const reduced = () => reduceQuery.matches || state.reduceManual;
const t = (s: Localized, vars: Record<string, string | number> = {}) =>
  s[state.lang].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
const current = (): AvatarDef | undefined => AVATARS.find((a) => a.id === state.id);

const $ = <T extends Element>(sel: string): T => {
  const el = document.querySelector<T>(sel);
  if (!el) throw new Error(`Missing ${sel}`);
  return el;
};

// ---------------------------------------------------------------------------------------------------------
// The stage: one character, big and small

interface StageView {
  svg: SVGSVGElement;
  size: number;
  crop: 'tile' | 'head';
  prefix: string;
}

let stageViews: StageView[] = [];

function stageSizes(def: AvatarDef): { size: number; crop: 'tile' | 'head'; label: string }[] {
  const list: { size: number; crop: 'tile' | 'head'; label: string }[] = [
    { size: 72, crop: 'tile', label: '72' },
    { size: 48, crop: 'tile', label: '48' },
    { size: 24, crop: 'tile', label: '24' },
  ];
  if (def.headBox) list.push({ size: 24, crop: 'head', label: `24 · ${t(UI.head)}` });
  return list;
}

function setStageFace(expression: Expression): void {
  const def = current();
  if (!def) return;
  for (const v of stageViews) {
    const face = v.svg.querySelector('.sfa-face');
    const box = viewBoxOf(def, v.crop);
    if (face)
      face.innerHTML = renderFace(def, expression, {
        size: (v.size * CANVAS) / box.size,
        idPrefix: v.prefix,
      });
    v.svg.dataset.expression = expression;
  }
}

function renderStage(): void {
  const def = current();
  const stage = $<HTMLElement>('#stage');
  if (!def) {
    stage.hidden = true;
    return;
  }
  stage.hidden = false;
  stopMotion();
  $<HTMLElement>('#ground').dataset.ground = state.ground;
  $('#big').innerHTML = renderAvatar(def, { expression: state.expression, size: 240, idPrefix: 'st-big' });
  $('#name-he').textContent = def.name.he;
  $('#name-en').textContent = def.name.en;
  $('#kind').textContent = t(KIND_ONE[def.kind]);
  const sizes = stageSizes(def);
  $('#small').innerHTML = sizes
    .map(
      (s, i) =>
        `<figure class="size"><div class="size-ground" data-view="${i}">${renderAvatar(def, {
          expression: state.expression,
          size: s.size,
          crop: s.crop,
          idPrefix: `st-${i}`,
        })}</div><figcaption>${s.label}</figcaption></figure>`,
    )
    .join('');
  stageViews = [{ svg: $<SVGSVGElement>('#big svg'), size: 240, crop: 'tile', prefix: 'st-big' }];
  sizes.forEach((s, i) =>
    stageViews.push({
      svg: $<SVGSVGElement>(`[data-view="${i}"] svg`),
      size: s.size,
      crop: s.crop,
      prefix: `st-${i}`,
    }),
  );
  renderFaces();
  renderButtons();
}

function renderFaces(): void {
  const def = current();
  if (!def) return;
  $('#faces').innerHTML = EXPRESSIONS.map(
    (e) =>
      `<button type="button" class="face" data-expression="${e}" aria-pressed="${e === state.expression}">` +
      renderAvatar(def, { expression: e, size: 64, idPrefix: `fx-${e}`, label: false }) +
      `<span>${t(EXPRESSION_NAMES[e])}</span></button>`,
  ).join('');
}

function renderButtons(): void {
  $('#expressions').innerHTML = EXPRESSIONS.map(
    (e) =>
      `<button type="button" class="chip" data-expression="${e}" aria-pressed="${e === state.expression}">${t(
        EXPRESSION_NAMES[e],
      )}</button>`,
  ).join('');
  $('#motions').innerHTML =
    MOTION_IDS.map(
      (id) =>
        `<button type="button" class="chip" data-motion="${id}" aria-pressed="${id === state.playing}">${t(
          MOTIONS[id].name,
        )}</button>`,
    ).join('') +
    `<button type="button" class="chip chip-strong" id="play-all" aria-pressed="${state.playAll}">${
      state.playAll ? t(UI.stop) : t(UI.playAll)
    }</button>`;
  renderStatus();
}

function renderStatus(): void {
  const def = current();
  const status = $<HTMLElement>('#status');
  if (!def || !state.playing) {
    status.textContent = reduced() ? t(UI.reducedNote) : ' ';
    return;
  }
  const m = resolveMotion(def, state.playing);
  const x = t(m.name);
  status.textContent =
    m.id === state.playing
      ? t(UI.playing, { x })
      : t(UI.playing, { x: t(UI.fallback, { x, y: t(MOTIONS[state.playing].name) }) });
}

// ---------------------------------------------------------------------------------------------------------
// Playing motions: CSS moves the parts (motion.ts motionCss), timers change the face

let timers: number[] = [];

function clearMotionClasses(svg: Element): void {
  for (const c of [...svg.classList]) if (c.startsWith('sfa-m-')) svg.classList.remove(c);
}

function stopMotion(): void {
  for (const id of timers) window.clearTimeout(id);
  timers = [];
  for (const v of stageViews) clearMotionClasses(v.svg);
  if (state.playing) setStageFace(state.expression);
  state.playing = null;
}

function play(id: MotionId): Promise<void> {
  const def = current();
  if (!def) return Promise.resolve();
  stopMotion();
  const m = resolveMotion(def, id);
  state.playing = id;
  renderButtons();
  for (const v of stageViews) {
    void v.svg.getBoundingClientRect(); // restart the animation
    v.svg.classList.add(`sfa-m-${m.id}`);
  }
  for (const c of faceChanges(m))
    timers.push(
      window.setTimeout(
        () => setStageFace(c.expression === 'base' ? state.expression : c.expression),
        c.atMs,
      ),
    );
  return new Promise((resolve) => {
    timers.push(
      window.setTimeout(() => {
        for (const v of stageViews) clearMotionClasses(v.svg);
        state.playing = null;
        renderButtons();
        resolve();
      }, m.durationMs + 40),
    );
  });
}

async function playAll(): Promise<void> {
  state.playAll = true;
  for (const id of MOTION_IDS) {
    if (!state.playAll) break;
    await play(id);
    await new Promise((r) => timers.push(window.setTimeout(r, 380)));
  }
  state.playAll = false;
  renderButtons();
}

/** Idle blinks: the stage character and, now and then, one character in the grid. */
function scheduleBlink(): void {
  window.setTimeout(
    () => {
      if (state.blink && !reduced()) {
        const targets: Element[] = state.playing ? [] : stageViews.map((v) => v.svg);
        const grid = [...document.querySelectorAll('#grid svg')];
        const pick = grid[Math.floor(Math.random() * grid.length)];
        if (pick) targets.push(pick);
        for (const svg of targets) {
          clearMotionClasses(svg);
          void svg.getBoundingClientRect();
          svg.classList.add('sfa-m-blink');
          window.setTimeout(() => svg.classList.remove('sfa-m-blink'), MOTIONS.blink.durationMs + 40);
        }
      }
      scheduleBlink();
    },
    2400 + Math.random() * 2800,
  );
}

// ---------------------------------------------------------------------------------------------------------
// The grid

function renderFilters(): void {
  const count = (f: Filter) => (f === 'all' ? AVATARS.length : AVATARS.filter((a) => a.kind === f).length);
  const label: Record<Filter, Localized> = {
    all: UI.filterAll,
    person: UI.person,
    animal: UI.animal,
    object: UI.object,
  };
  $('#filters').innerHTML = (['all', ...AVATAR_KINDS] as Filter[])
    .map(
      (f) =>
        `<button type="button" class="chip" data-filter="${f}" aria-pressed="${f === state.filter}">${t(
          label[f],
        )} <span class="count">${count(f)}</span></button>`,
    )
    .join('');
}

function renderGrid(): void {
  const list = AVATARS.filter((a) => state.filter === 'all' || a.kind === state.filter);
  $('#grid').innerHTML = list.length
    ? list
        .map(
          (a) =>
            `<button type="button" class="card" data-id="${a.id}" aria-pressed="${a.id === state.id}" aria-label="${
              a.name[state.lang]
            }">${renderAvatar(a, { size: 88, idPrefix: `g-${a.id}`, label: false })}<span class="card-name">${
              a.name[state.lang]
            }</span></button>`,
        )
        .join('')
    : `<p class="empty">${t(UI.empty)}</p>`;
}

// ---------------------------------------------------------------------------------------------------------
// Text, language, wiring

function renderText(): void {
  const root = $<HTMLElement>('#app');
  root.lang = state.lang;
  root.dir = state.lang === 'he' ? 'rtl' : 'ltr';
  for (const el of document.querySelectorAll<HTMLElement>('[data-t]')) {
    const key = el.dataset.t as keyof typeof UI | undefined;
    if (key && key in UI) el.textContent = t(UI[key]);
  }
  $('#lead').textContent = t(UI.lead, { n: AVATARS.length, e: EXPRESSIONS.length, m: MOTION_IDS.length });
  $('#lang').textContent = t(UI.otherLang);
  // The command is LTR inside RTL text: isolate it so its punctuation stays put.
  $('#footer').innerHTML = t(UI.footer, {
    cmd: '<code dir="ltr">npm run preview -w @sudoku-fight/avatars</code>',
  });
  $<HTMLInputElement>('#opt-blink').checked = state.blink;
  $<HTMLInputElement>('#opt-reduce').checked = state.reduceManual;
  for (const b of document.querySelectorAll<HTMLButtonElement>('[data-ground]'))
    b.setAttribute('aria-pressed', String(b.dataset.ground === state.ground));
}

function renderAll(): void {
  renderText();
  renderFilters();
  renderGrid();
  renderStage();
}

function setExpression(e: Expression): void {
  state.expression = e;
  stopMotion();
  setStageFace(e);
  for (const b of document.querySelectorAll<HTMLElement>('[data-expression]'))
    if (b.tagName === 'BUTTON') b.setAttribute('aria-pressed', String(b.dataset.expression === e));
}

document.addEventListener('click', (ev) => {
  const el = (ev.target as Element | null)?.closest<HTMLElement>('button');
  if (!el) return;
  const d = el.dataset;
  if (d.id) {
    state.id = d.id;
    state.expression = 'neutral';
    state.playAll = false;
    renderGrid();
    renderStage();
    if (window.innerWidth < 760) $('#stage').scrollIntoView({ behavior: reduced() ? 'auto' : 'smooth' });
  } else if (d.filter) {
    state.filter = d.filter as Filter;
    renderFilters();
    renderGrid();
  } else if (d.expression) {
    state.playAll = false;
    setExpression(d.expression as Expression);
    renderButtons();
  } else if (d.motion) {
    state.playAll = false;
    void play(d.motion as MotionId);
  } else if (el.id === 'play-all') {
    if (state.playAll) {
      state.playAll = false;
      stopMotion();
      renderButtons();
    } else void playAll();
  } else if (d.ground) {
    state.ground = d.ground as Ground;
    store.set('ground', state.ground);
    $<HTMLElement>('#ground').dataset.ground = state.ground;
    renderText();
  } else if (el.id === 'lang') {
    state.lang = state.lang === 'he' ? 'en' : 'he';
    store.set('lang', state.lang);
    renderAll();
  }
});

$<HTMLInputElement>('#opt-blink').addEventListener('change', (ev) => {
  state.blink = (ev.target as HTMLInputElement).checked;
});
$<HTMLInputElement>('#opt-reduce').addEventListener('change', (ev) => {
  state.reduceManual = (ev.target as HTMLInputElement).checked;
  document.documentElement.classList.toggle('sfa-reduce', state.reduceManual);
  renderStatus();
});
reduceQuery.addEventListener('change', renderStatus);

renderAll();
scheduleBlink();
